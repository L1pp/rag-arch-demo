-- Initial durable multi-user web schema.  Authentication SQLite remains a
-- separate legacy source; explicit import copies users, never legacy sessions.
-- All timestamps use UTC Unix epoch seconds to match the existing auth store.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    username_key TEXT NOT NULL UNIQUE,
    password_salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    password_iterations INTEGER NOT NULL CHECK (password_iterations > 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    CHECK (char_length(username) BETWEEN 1 AND 64)
);

CREATE TABLE sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    CHECK (expires_at > created_at)
);
CREATE INDEX sessions_user_id_idx ON sessions(user_id);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);

CREATE TABLE workspaces (
    workspace_id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    last_event_seq BIGINT NOT NULL DEFAULT 0 CHECK (last_event_seq >= 0),
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    UNIQUE (user_id, workspace_id)
);

CREATE TABLE assistant_slots (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assistant_id TEXT NOT NULL CHECK (assistant_id IN ('chat', 'standards', 'plan')),
    active_task_id TEXT,
    history_generation BIGINT NOT NULL DEFAULT 0 CHECK (history_generation >= 0),
    updated_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, assistant_id)
);

CREATE TABLE tasks (
    task_id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    workspace_id TEXT NOT NULL,
    assistant_id TEXT NOT NULL CHECK (assistant_id IN ('chat', 'standards', 'plan')),
    request_id TEXT NOT NULL CHECK (char_length(request_id) BETWEEN 1 AND 128),
    inputs JSONB NOT NULL DEFAULT '{}'::JSONB,
    status TEXT NOT NULL CHECK (status IN (
        'queued', 'running', 'cancelling', 'recovering',
        'completed', 'failed', 'cancelled'
    )),
    generation BIGINT NOT NULL DEFAULT 0 CHECK (generation >= 0),
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    worker_instance TEXT,
    attempt_token TEXT,
    lease_until DOUBLE PRECISION,
    stage TEXT NOT NULL DEFAULT 'queued',
    detail TEXT NOT NULL DEFAULT '',
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    started_at DOUBLE PRECISION,
    finished_at DOUBLE PRECISION,
    result JSONB,
    error TEXT,
    UNIQUE (user_id, assistant_id, request_id),
    UNIQUE (user_id, assistant_id, task_id),
    UNIQUE (user_id, workspace_id, task_id),
    FOREIGN KEY (user_id, workspace_id)
        REFERENCES workspaces(user_id, workspace_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id, assistant_id)
        REFERENCES assistant_slots(user_id, assistant_id) ON DELETE CASCADE
);
CREATE INDEX tasks_owner_workspace_created_idx
    ON tasks(user_id, workspace_id, created_at DESC);
CREATE INDEX tasks_queue_dispatch_idx
    ON tasks(status, created_at, user_id, assistant_id)
    WHERE status = 'queued';
CREATE UNIQUE INDEX tasks_one_active_per_assistant_uq
    ON tasks(user_id, assistant_id)
    WHERE status IN ('queued', 'running', 'cancelling', 'recovering');
CREATE INDEX tasks_worker_lease_idx
    ON tasks(status, lease_until)
    WHERE status IN ('running', 'cancelling', 'recovering');

-- The slot can point to a task created in the same transaction.  Deferring
-- this FK also permits the task and slot update to commit atomically.
ALTER TABLE assistant_slots
    ADD CONSTRAINT assistant_slots_active_task_fk
    FOREIGN KEY (user_id, assistant_id, active_task_id)
    REFERENCES tasks(user_id, assistant_id, task_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE attachments (
    attachment_id TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    workspace_id TEXT NOT NULL,
    filename TEXT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,
    content_type TEXT,
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    status TEXT NOT NULL DEFAULT 'ready'
        CHECK (status IN ('processing', 'ready', 'failed', 'deleting')),
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, workspace_id, attachment_id),
    FOREIGN KEY (user_id, workspace_id)
        REFERENCES workspaces(user_id, workspace_id) ON DELETE CASCADE
);
CREATE INDEX attachments_owner_workspace_created_idx
    ON attachments(user_id, workspace_id, created_at DESC);

CREATE TABLE task_attachments (
    user_id BIGINT NOT NULL,
    workspace_id TEXT NOT NULL,
    task_id TEXT NOT NULL,
    attachment_id TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, task_id, attachment_id),
    FOREIGN KEY (user_id, workspace_id, task_id)
        REFERENCES tasks(user_id, workspace_id, task_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id, workspace_id, attachment_id)
        REFERENCES attachments(user_id, workspace_id, attachment_id) ON DELETE CASCADE
);
CREATE INDEX task_attachments_owner_attachment_idx
    ON task_attachments(user_id, workspace_id, attachment_id);

CREATE TABLE workspace_events (
    user_id BIGINT NOT NULL,
    workspace_id TEXT NOT NULL,
    seq BIGINT NOT NULL CHECK (seq > 0),
    event_type TEXT NOT NULL,
    task_id TEXT,
    payload JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (workspace_id, seq),
    FOREIGN KEY (user_id, workspace_id)
        REFERENCES workspaces(user_id, workspace_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id, workspace_id, task_id)
        REFERENCES tasks(user_id, workspace_id, task_id) ON DELETE CASCADE
);
CREATE INDEX workspace_events_owner_cursor_idx
    ON workspace_events(user_id, workspace_id, seq);

CREATE TABLE scheduler_state (
    singleton_key TEXT PRIMARY KEY CHECK (singleton_key = 'global'),
    global_execution_limit INTEGER NOT NULL CHECK (global_execution_limit > 0),
    fairness_cursor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
INSERT INTO scheduler_state(
    singleton_key, global_execution_limit, fairness_cursor_user_id, updated_at
) VALUES (
    'global', 1, NULL, EXTRACT(EPOCH FROM clock_timestamp())
) ON CONFLICT (singleton_key) DO NOTHING;
